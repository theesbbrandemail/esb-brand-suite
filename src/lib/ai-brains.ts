export interface ExecutedActionResult {
  actionId: string;
  type: string;
  summary: string;
  success: boolean;
  data?: any;
}

/**
 * Parses user message for executive commands and executes them on the system!
 */
export function executeAdminAction(
  brain: AiBrainId,
  command: string,
  contextSnapshot?: any
): { response: string; executedAction?: ExecutedActionResult } {
  const lower = command.toLowerCase();
  const brainMeta = AI_BRAINS[brain];

  // 0. GENERATE INVOICE ACTION
  if (lower.includes("invoice") || lower.includes("bill client") || lower.includes("generate invoice") || lower.includes("create invoice")) {
    const nameMatch = command.match(/(?:for|client|to)\s+([A-Za-z\s]+?)(?:\s+₦|\s+\d|\s+for|\s+at|$)/i);
    const clientName = nameMatch && nameMatch[1].trim() ? nameMatch[1].trim() : "Chief Adewale Adeleke";
    const valMatch = command.match(/(\d+[\d,.]*)/);
    let amount = valMatch ? parseInt(valMatch[1].replace(/,/g, ""), 10) : 450_000;
    if (amount < 1000) amount = amount * 1000;

    let brandTarget: InvoiceReceipt["brand"] = "Derma Aesthetics";
    if (lower.includes("skincare") || lower.includes("kitchen")) brandTarget = "Skincare Kitchen";
    else if (lower.includes("clinic")) brandTarget = "Skin Clinic";
    else if (lower.includes("dental")) brandTarget = "Dental Care";
    else if (lower.includes("rejuvenat")) brandTarget = "Rejuvenating Aesthetics";

    const inv = createInvoice({
      brand: brandTarget,
      clientName,
      clientEmail: `${clientName.toLowerCase().replace(/\s+/g, ".")}@gmail.com`,
      clientPhone: "+234 803 884 1029",
      items: [
        {
          description: `${brandTarget} Clinical & Aesthetic Package`,
          quantity: 1,
          unitPriceNgn: amount,
        },
      ],
      discountNgn: 0,
      notes: `Automated Tax Invoice generated by ${brainMeta.name} Executive AI.`,
      createdBy: `${brainMeta.name} Autonomous System`,
    });

    const action: AiActionExecution = {
      id: `act-${Date.now()}`,
      brain: brainMeta.name as any,
      command,
      actionType: "GENERATE_INVOICE",
      details: `Generated Tax Invoice ${inv.id} for ${clientName} valued at ₦${inv.totalAmountNgn.toLocaleString()} (Subtotal ₦${inv.subtotalNgn.toLocaleString()} + 7.5% VAT ₦${inv.vatNgn.toLocaleString()}).`,
      targetEntity: inv.id,
      status: "executed",
      timestamp: "Just now",
      impactValueNgn: inv.totalAmountNgn,
    };
    saveStoredAiActions([action, ...getStoredAiActions()]);

    return {
      response: `🧾 **Tax Invoice Auto-Generated by ${brainMeta.name}:**\n\n- **Invoice No:** **${inv.id}**\n- **Client:** ${inv.clientName}\n- **Brand:** ${inv.brand}\n- **Subtotal:** ₦${inv.subtotalNgn.toLocaleString()}\n- **VAT (7.5%):** ₦${inv.vatNgn.toLocaleString()}\n- **Total Amount Due:** **₦${inv.totalAmountNgn.toLocaleString()} NGN**\n- **Bank Details:** ${inv.bankAccount.bankName} (Acct: ${inv.bankAccount.accountNumber})\n- **Verification Hash:** \`${inv.verificationHash}\`\n\nThe invoice has been saved to the Billing System and is ready for PDF export or instant WhatsApp/Email dispatch!`,
      executedAction: {
        actionId: action.id,
        type: "GENERATE_INVOICE",
        summary: `Created Invoice ${inv.id} for ${clientName} (₦${inv.totalAmountNgn.toLocaleString()})`,
        success: true,
        data: inv,
      },
    };
  }

  // 0.1 GENERATE PAYMENT RECEIPT ACTION
  if (lower.includes("receipt") || lower.includes("generate receipt") || lower.includes("issue receipt") || lower.includes("confirm payment")) {
    const nameMatch = command.match(/(?:for|client|to)\s+([A-Za-z\s]+?)(?:\s+₦|\s+\d|\s+for|\s+at|$)/i);
    const clientName = nameMatch && nameMatch[1].trim() ? nameMatch[1].trim() : "Senator Fatima Aliyu";
    const valMatch = command.match(/(\d+[\d,.]*)/);
    let amount = valMatch ? parseInt(valMatch[1].replace(/,/g, ""), 10) : 750_000;
    if (amount < 1000) amount = amount * 1000;

    const receipt = createReceipt({
      brand: "Derma Aesthetics",
      clientName,
      clientEmail: `${clientName.toLowerCase().replace(/\s+/g, ".")}@gov.ng`,
      clientPhone: "+234 809 111 8899",
      items: [
        {
          description: "VIP Executive Clinical Consultation & Regimen Dispensation",
          quantity: 1,
          unitPriceNgn: amount,
        },
      ],
      paymentMethod: "zenith_bank_transfer",
      paymentReference: `ZEN-${Date.now().toString().slice(-8)}`,
      amountPaidNgn: amount,
      notes: `Official Stamped Payment Receipt authorized by ${brainMeta.name}.`,
      createdBy: `${brainMeta.name} Autonomous System`,
    });

    const action: AiActionExecution = {
      id: `act-${Date.now()}`,
      brain: brainMeta.name as any,
      command,
      actionType: "GENERATE_RECEIPT",
      details: `Issued Stamped Official Payment Receipt ${receipt.id} for ${clientName} — ₦${amount.toLocaleString()} received via Zenith Bank.`,
      targetEntity: receipt.id,
      status: "executed",
      timestamp: "Just now",
      impactValueNgn: amount,
    };
    saveStoredAiActions([action, ...getStoredAiActions()]);

    return {
      response: `💳 **Official Payment Receipt Issued by ${brainMeta.name}:**\n\n- **Receipt No:** **${receipt.id}**\n- **Paid by:** ${receipt.clientName}\n- **Amount Received:** **₦${amount.toLocaleString()} NGN**\n- **Payment Method:** Zenith Bank Transfer (Ref: \`${receipt.paymentReference}\`)\n- **Verification Seal:** \`${receipt.verificationHash}\`\n- **Status:** **PAID IN FULL**\n\nRecorded immediately in the Revenue Ledger and CRM client profile.`,
      executedAction: {
        actionId: action.id,
        type: "GENERATE_RECEIPT",
        summary: `Issued Receipt ${receipt.id} for ${clientName} (₦${amount.toLocaleString()})`,
        success: true,
        data: receipt,
      },
    };
  }

  // 0.2 PAYMENT INFORMATION & BANK DETAILS DISPATCH
  if (lower.includes("payment info") || lower.includes("bank account") || lower.includes("account number") || lower.includes("how to pay")) {
    const zenith = ESB_CORPORATE_BANKS.zenith;
    const gtbank = ESB_CORPORATE_BANKS.gtbank;
    const providus = ESB_CORPORATE_BANKS.providus;

    return {
      response: `🏦 **Official ESB Brand Group Payment Coordinates:**\n\n1. **Primary Settlement (Zenith Bank PLC)**\n   - **Account Name:** ${zenith.accountName}\n   - **Account Number:** **\`${zenith.accountNumber}\`**\n   - **Sort Code:** ${zenith.sortCode}\n\n2. **Secondary Settlement (GTBank PLC)**\n   - **Account Name:** ${gtbank.accountName}\n   - **Account Number:** **\`${gtbank.accountNumber}\`**\n\n3. **VIP Instant Virtual Account (Providus Bank)**\n   - **Account Name:** ${providus.accountName}\n   - **Virtual Account:** **\`${providus.accountNumber}\`** *(Auto-reconciles within 3 seconds)*\n\n*All payments reflect immediately in the live Cashflow and Accountant audit logs.*`,
    };
  }

  // 1. RESTOCK INVENTORY ACTION
  if (lower.includes("restock") || lower.includes("reorder") || lower.includes("stock up") || lower.includes("order more")) {
    const qtyMatch = command.match(/\b(\d+)\b/);
    const qty = qtyMatch ? parseInt(qtyMatch[1], 10) : 50;
    let product = "Vitamin C Brightening Serum";
    if (lower.includes("retinol")) product = "Retinol Night Repair";
    else if (lower.includes("hydrafacial")) product = "Hydrafacial Solution Kit";
    else if (lower.includes("whitening") || lower.includes("dental")) product = "Whitening Gel Pro";
    else if (lower.includes("ceramide")) product = "Ceramide Barrier Cream";
    else if (lower.includes("peel")) product = "Chemical Peel Solution";

    const poNumber = `ESB-PO-${Math.floor(1000 + Math.random() * 9000)}`;
    const cost = qty * 9500; // in NGN

    const action: AiActionExecution = {
      id: `act-${Date.now()}`,
      brain: brainMeta.name as any,
      command,
      actionType: "RESTOCK_INVENTORY",
      details: `Dispatched Purchase Order ${poNumber} for ${qty} units of ${product}. Value: ₦${cost.toLocaleString()} to Central Formulation Lab.`,
      targetEntity: product,
      status: "executed",
      timestamp: "Just now",
      impactValueNgn: cost,
    };

    const actions = getStoredAiActions();
    saveStoredAiActions([action, ...actions]);

    return {
      response: `⚡ **Action Auto-Executed by ${brainMeta.name}:**\n\nI have generated and authorized Purchase Order **${poNumber}** for **${qty} units** of **${product}** at estimated supplier cost of **₦${cost.toLocaleString()}**.\n\n- **Destination:** Port Harcourt Central Formulation Lab\n- **Status:** Transmitted to Logistics & Formulations\n- **Inventory update:** Auto-synced in the Inventory & Operations Dashboard.`,
      executedAction: {
        actionId: action.id,
        type: "RESTOCK_INVENTORY",
        summary: `PO ${poNumber}: Restocked ${qty} units of ${product}`,
        success: true,
        data: action,
      },
    };
  }

  // 2. CREATE CRM LEAD / CLIENT
  if (
    lower.includes("add lead") ||
    lower.includes("new client") ||
    lower.includes("new lead") ||
    lower.includes("add patient") ||
    lower.includes("create lead")
  ) {
    const nameMatch = command.match(/(?:add lead|new client|lead|client|patient)\s+([A-Za-z\s]+?)(?:\s+₦|\s+\d|\s+for|\s+at|$)/i);
    const clientName = nameMatch && nameMatch[1].trim() ? nameMatch[1].trim() : "Alhaji Farouk Bello";

    // Value extraction
    const valMatch = command.match(/(\d+[\d,.]*)/);
    let val = valMatch ? parseInt(valMatch[1].replace(/,/g, ""), 10) : 1_500_000;
    if (val < 1000) val = val * 1000; // handle 500k notation

    const newDeal: SalesDeal = {
      id: `deal-${Date.now()}`,
      clientName,
      phone: "+234 803 " + Math.floor(1000000 + Math.random() * 9000000),
      department: lower.includes("derma")
        ? "derma"
        : lower.includes("dental")
        ? "dental"
        : lower.includes("skincare")
        ? "skincare-kitchen"
        : "skinclinic",
      packageName: "VIP Executive Treatment Plan",
      value: val,
      stage: "proposal",
      assignedRep: "Chioma Okeke",
      createdAt: new Date().toISOString(),
      notes: `Generated via ${brainMeta.name} Executive AI Instruction.`,
    };

    const deals = getStoredDeals();
    saveStoredDeals([newDeal, ...deals]);

    const newPatient: CrmPatient = {
      id: `crm-${Date.now()}`,
      name: clientName,
      phone: newDeal.phone,
      email: `${clientName.toLowerCase().replace(/\s+/g, ".")}@executive.ng`,
      tier: val > 2_000_000 ? "VIP Concierge" : "Gold Elite",
      lifetimeSpend: val,
      lastVisit: "Today (Lead Generated)",
      primaryBranch: "Port Harcourt Flagship",
      preferredBrand: "Derma Aesthetics",
      loyaltyPoints: Math.round(val / 1000),
      notes: "Enrolled automatically via AI command interface.",
      treatmentHistory: [],
    };

    const patients = getStoredPatients();
    saveStoredPatients([newPatient, ...patients]);

    const action: AiActionExecution = {
      id: `act-${Date.now()}`,
      brain: brainMeta.name as any,
      command,
      actionType: "ADD_LEAD",
      details: `Created new VIP client profile and sales deal for ${clientName} valued at ₦${val.toLocaleString()}.`,
      targetEntity: clientName,
      status: "executed",
      timestamp: "Just now",
      impactValueNgn: val,
    };
    saveStoredAiActions([action, ...getStoredAiActions()]);

    return {
      response: `🎯 **Client & Pipeline Record Created:**\n\n- **Client:** ${clientName}\n- **Deal Value:** ₦${val.toLocaleString()} NGN\n- **Department:** ${newDeal.department.toUpperCase()}\n- **Assigned Rep:** Chioma Okeke (Executive Concierge)\n- **CRM Sync:** Registered into persistent CRM database with loyalty tier **${newPatient.tier}**.\n\nYou can see this live under the **Sales Dashboard** and **CRM Clients** tabs immediately!`,
      executedAction: {
        actionId: action.id,
        type: "ADD_LEAD",
        summary: `Created deal ₦${val.toLocaleString()} for ${clientName}`,
        success: true,
        data: newDeal,
      },
    };
  }

  // 3. STAFF CLOCK-IN / GEO VERIFICATION OVERRIDE
  if (lower.includes("clock in") || lower.includes("sign in staff") || lower.includes("verify staff") || lower.includes("attendance")) {
    const staffList = getStoredStaff();
    const targetStaff = staffList[0]; // Lead Doctor or specified

    const updated = staffList.map((s) => ({
      ...s,
      status: "on_duty" as const,
      clockInTime: s.clockInTime || new Date().toLocaleTimeString("en-NG", { hour: "2-digit", minute: "2-digit" }),
      verifiedLocation: "Port Harcourt Flagship Clinic & Depot (GPS Verified & Geo-Locked)",
    }));
    saveStoredStaff(updated);

    const action: AiActionExecution = {
      id: `act-${Date.now()}`,
      brain: brainMeta.name as any,
      command,
      actionType: "VERIFY_STAFF",
      details: `Executive authorization: Verified GPS premises location for all on-duty medical and front-desk personnel.`,
      targetEntity: "Staff Attendance Registry",
      status: "executed",
      timestamp: "Just now",
    };
    saveStoredAiActions([action, ...getStoredAiActions()]);

    return {
      response: `🛡️ **Geo-Fenced Staff Attendance Verified:**\n\nI have confirmed premise proximity check at **Port Harcourt Flagship Clinic (4.8156° N, 7.0498° E)**.\n\n- **Verified Staff On-Duty:** ${updated.length} team members\n- **Location Check:** Lat/Long within 100m geofence radius\n- **Biometric Token:** Authenticated\n- **Status:** All shifts marked Active in the Staff Records System.`,
      executedAction: {
        actionId: action.id,
        type: "VERIFY_STAFF",
        summary: `Geo-verified ${updated.length} staff attendance at Port Harcourt Flagship`,
        success: true,
        data: updated,
      },
    };
  }

  // 4. DISCOUNT / PROMO CODE CREATION
  if (lower.includes("discount") || lower.includes("promo") || lower.includes("coupon") || lower.includes("code")) {
    const pctMatch = command.match(/(\d+)%/);
    const pct = pctMatch ? pctMatch[1] : "15";
    const promoCode = `ESB-VIP-${pct}-${Math.floor(100 + Math.random() * 900)}`;

    const action: AiActionExecution = {
      id: `act-${Date.now()}`,
      brain: brainMeta.name as any,
      command,
      actionType: "EXECUTIVE_OVERRIDE",
      details: `Generated executive authorization code ${promoCode} for ${pct}% off luxury consultations.`,
      targetEntity: promoCode,
      status: "executed",
      timestamp: "Just now",
    };
    saveStoredAiActions([action, ...getStoredAiActions()]);

    return {
      response: `✨ **Executive Discount Authorized:**\n\n- **Code:** \`${promoCode}\`\n- **Discount:** **${pct}% OFF**\n- **Applicability:** All aesthetic, dental, and skincare consultations across Lagos & Abuja\n- **Audit Status:** Recorded in CEO Executive Ledger.`,
      executedAction: {
        actionId: action.id,
        type: "EXECUTIVE_OVERRIDE",
        summary: `Created ${pct}% code ${promoCode}`,
        success: true,
      },
    };
  }

  // 5. STRATEGIC INTELLIGENCE / DEFAULT RESPONSE
  const deals = getStoredDeals();
  const totalRevenue = deals.reduce((acc, d) => acc + d.value, 0);
  const staff = getStoredStaff();
  const onDutyCount = staff.filter((s) => s.status === "on_duty").length;

  return {
    response: `✦ **${brainMeta.name} Strategic Briefing:**\n\nHere is the real-time operational status for **ESB Brand Suite**:\n\n- **Total Active Pipeline:** ₦${totalRevenue.toLocaleString()} NGN across 5 clinical departments\n- **Staff on Premises:** ${onDutyCount} / ${staff.length} staff verified on-duty at Port Harcourt & Abuja\n- **Top Performing Unit:** Derma Aesthetics & Skincare Kitchen\n- **Executive Directives Ready:** You can instruct me to *\"Restock 100 Vitamin C serums\"*, *\"Add VIP lead Alhaji Dangote ₦5,000,000\"*, *\"Verify staff attendance\"*, or *\"Issue 20% discount code\"* and I will execute it automatically!`,
  };
}
